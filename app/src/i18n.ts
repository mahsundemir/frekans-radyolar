// Uygulama dili = yayın dili. Kullanıcı bir radyo dili seçince arayüz de o dile geçer.
// Dil kodları stations.json içindeki `languages[].code` ile aynı. Çevirisi olmayan bir yayın dili
// (ör. Kürtçe, "ku") Türkçe arayüzle gösterilir.

export type UiLang = 'tr' | 'en' | 'es' | 'ar' | 'de' | 'fr' | 'ru';

export const UI_LANGS: UiLang[] = ['tr', 'en', 'es', 'ar', 'de', 'fr', 'ru'];
export const DEFAULT_LANG: UiLang = 'tr';

export function uiLang(code: string | undefined | null): UiLang {
  return (UI_LANGS as string[]).includes(code ?? '') ? (code as UiLang) : DEFAULT_LANG;
}

// Büyük/küçük harf dönüşümünde kullanılacak yerel ayar ("i" → "İ" yalnızca Türkçede)
export function localeOf(code: string): string {
  return uiLang(code);
}

// İlk açılışta cihaz dilini seç; desteklenmiyorsa Türkçe
export function detectLanguage(): UiLang {
  try {
    const loc = Intl.DateTimeFormat().resolvedOptions().locale || '';
    return uiLang(loc.toLowerCase().split(/[-_]/)[0]);
  } catch {
    return DEFAULT_LANG;
  }
}

