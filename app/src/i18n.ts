const DICTS: Record<UiLang, Dict> = {tr, en, es, ar, de, fr, ru};

export type Vars = Record<string, string | number>;

export function translate(code: string, key: Key, vars?: Vars): string {
  const raw = DICTS[uiLang(code)][key] ?? tr[key];
  if (!vars) {
    return raw;
  }
  return raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
